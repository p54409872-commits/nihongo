function teRuleTxt(ch,k,ta){
  const T=ta?["った","んだ","いた","いだ","した"]:["って","んで","いて","いで","して"];
  if(k==="行く") return `「行く」是例外：→「行${ta?"った":"って"}」`;
  if("うつる".includes(ch)) return `词尾「う・つ・る」→「${T[0]}」`;
  if("むぶぬ".includes(ch)) return `词尾「む・ぶ・ぬ」→「${T[1]}」`;
  if(ch==="く") return `词尾「く」→「${T[2]}」`;
  if(ch==="ぐ") return `词尾「ぐ」→「${T[3]}」`;
  return `词尾「す」→「${T[4]}」`;
}

function ruleText(st,op,res){
  const k=st.k,out=res.k;
  if(["masen","mashita","mashou","msd"].includes(op)) return `${HINT[op]}：${k} → ${out}`;
  if(["adjPast","adjTe","adjBa"].includes(op)) return `「〜ない」的变化和い形容词一样，${HINT[op]}：${k} → ${out}`;
  if(op==="tara") return `在た形后面加「ら」：${k} → ${out}`;
  if(op==="teiru") return `先变成て形，再加「いる」：${k} → ${out}`;
  if(st.t==="g"){
    const ch=k.slice(-1),R=ROW[ch];
    const m={
      masu:`词尾う段假名「${ch}」→ 换成同行い段「${R[1]}」，再加「ます」`,
      nai:`词尾う段假名「${ch}」→ 换成同行あ段「${R[0]}」${ch==="う"?"（う结尾要变成「わ」，不是「あ」）":""}，再加「ない」`,
      pot:`词尾「${ch}」→ 换成同行え段「${R[3]}」，再加「る」`,
      pas:`词尾「${ch}」→ 换成同行あ段「${R[0]}」，再加「れる」`,
      cau:`词尾「${ch}」→ 换成同行あ段「${R[0]}」，再加「せる」`,
      cp:`词尾「${ch}」→ 换成同行あ段「${R[0]}」，再加「せられる」（${ch!=="す"?"也可以缩短成「される」":"す结尾不能缩短"}）`,
      ba:`词尾「${ch}」→ 换成同行え段「${R[3]}」，再加「ば」`,
      vol:`词尾「${ch}」→ 换成同行お段「${R[4]}」，再加「う」`,
      imp:`词尾「${ch}」→ 换成同行え段「${R[3]}」`,
      te:teRuleTxt(ch,k,false),
      ta:teRuleTxt(ch,k,true)
    };
    return `一类动词规则：${m[op]||HINT[op]||""}：${k} → ${out}`;
  }
  if(st.t==="i"){
    const m={masu:"去掉词尾「る」，再加「ます」",nai:"去掉「る」，再加「ない」",te:"去掉「る」，再加「て」",ta:"去掉「る」，再加「た」",
      pot:"去掉「る」，再加「られる」（不要说成ら抜き的「れる」）",pas:"去掉「る」，再加「られる」（和可能形同形）",
      cau:"去掉「る」，再加「させる」",cp:"去掉「る」，再加「させられる」",ba:"去掉「る」，再加「れば」",
      vol:"去掉「る」，再加「よう」",imp:"去掉「る」，再加「ろ」"};
    const derived=st.voice||st.teiru;
    return `${derived?`变成「${k}」之后，按二类动词规则变`:"二类动词规则"}：${m[op]||HINT[op]||""}：${k} → ${out}`;
  }
  if(st.t==="s"){
    const m={masu:"する→します",nai:"する→しない",te:"する→して",ta:"する→した",pot:"する→できる",pas:"する→される",
      cau:"する→させる",cp:"する→させられる",ba:"する→すれば",vol:"する→しよう",imp:"する→しろ"};
    return `三类动词（する）规则：${m[op]||HINT[op]||""}：${k} → ${out}`;
  }
  if(st.t==="k") return `三类动词（来る）规则，读音会变：${HINT[op]||""}：${k}（${st.r}）→ ${out}（${res.r}）`;
  return `${HINT[op]||""}：${k} → ${out}`;
}

function specDiag(val,st,op,verb){
  const hit=f=>f&&(val===f.k||val===f.r);
  if(st.t==="g"){
    let w=null;
    try{w=OPS[op].fn({...st,t:"i"});}catch(e){}
    if(hit(w)){
      const trap=/[いきしちにひみりぎじびえけせてねへめれげべ]る$/.test(st.r);
      return `你把「${st.k}」当成了二类动词（直接去掉「る」）。「${verb.k}」是一类动词${trap?"（看起来像二类，其实是例外，要特别记住）":""}，要按一类变。`;
    }
  }
  if(st.t==="i"){
    let w=null;
    try{w=OPS[op].fn({...st,t:"g"});}catch(e){}
    if(hit(w)) return st.voice||st.teiru
      ?`变成「${st.k}」之后要按二类动词变（去掉「る」再接），你按一类动词变了。`
      :`你把「${st.k}」当成了一类动词。「${st.k}」是二类动词，要去掉「る」再接。`;
  }
  if(typeof nmList==="function"&&!st.voice&&!st.teiru&&st.t===verb.t&&st.k===verb.k){
    const nm=nmList(verb,op);
    if(nm.includes(val)) return `「${val}」是常见的错误写法，注意看下面的规则。`;
  }
  return null;
}

const _chainDetailBeforeExplain=window.chainDetail;
window.chainDetail=function(val,ok){
  let h=_chainDetailBeforeExplain(val,ok);
  try{
    const verb=chain.verb,steps=chain.steps,t=steps[j];
    const st=j?steps[j-1]:base(verb);
    if(!ok){
      const g=diagnose(val);
      if(g.indexOf("形式不对")===0){
        const sp=specDiag(val,st,t.op,verb);
        if(sp) h=h.replace(`<div class="diag">${g}</div>`,`<div class="diag">❗ ${sp}</div>`);
      }
    }
    const tr=TRANS[verb.k];
    const conf=[];
    if(VCONF[verb.k]) conf.push(VCONF[verb.k]);
    if(OPNOTE[t.op]) conf.push(OPNOTE[t.op]);
    const block=`<div class="explain"><b>📘 规则讲解</b>
      <div>${esc(ruleText(st,t.op,t))}</div>
      ${tr?`<div>🔄 自他：「${verb.k}」是${tr[0]}动词${tr[2]?"（"+esc(tr[2])+"）":""}${tr[1]?"。对应的"+esc(tr[1]):""}</div>`:""}
      ${conf.length?`<div>⚠ 容易混淆：${esc(conf.join("；"))}</div>`:""}
    </div>`;
    const mark="<h3>一、完整变形路线</h3>";
    h=h.indexOf(mark)>=0?h.replace(mark,block+mark):h+block;
  }catch(e){console.error(e);}
  return h;
};
